#!/usr/bin/env bash
# Converts the painted source art (docs/art, on black) into game textures in
# Rageborn/Media/Art and writes Rageborn/PaintedList.lua.
#   sides  1024x1536 -> 256x512   drawn left of the character and mirrored on the right
#   top    1536x1024 -> 512x256   drawn above the head
#   emblem 1024x1024 -> 256x256   a small centred piece, drawn above the head
# docs/art/legacy holds the old-game look: same layouts, files named legacy_*, listed in the
# gallery's Legacy menu.
# Textures need power-of-two sizes; the addon draws them at the source's proportions.
set -e
cd "$(dirname "$0")/.."
OUT=Rageborn/Media/Art; mkdir -p "$OUT"; rm -f "$OUT"/*.tga
TMP=$(mktemp -d); LIST="$TMP/list"; : > "$LIST"
conv() { # src file alert layout w h label [extra list fields]
  cat > "$TMP/p.html" <<HTML
<body style="margin:0;width:$5px;height:$6px;background:#000 url(file://$PWD/$1) 0 0/$5px $6px no-repeat"></body>
HTML
  google-chrome --headless=new --no-sandbox --disable-gpu --hide-scrollbars --allow-file-access-from-files \
    --window-size=$5,$6 --screenshot="$TMP/p.png" "file://$TMP/p.html" >/dev/null 2>&1
  python3 -I tools/png2tga.py "$TMP/p.png" "$OUT/$2.tga"
  printf '    { file = "%s", alert = "%s", layout = "%s", label = "%s"%s },\n' "$2" "$3" "$4" "$7" "${8:-}" >> "$LIST"
  echo "  $2"
}
name() { echo "$1" | sed -E 's/([a-z])([A-Z])/\1 \2/g; s/^./\U&/'; }
for dir in docs/art/around/*/; do
  key=$(basename "$dir")
  for f in "$dir$key"_side*.png; do [ -f "$f" ] || continue
    n=$(basename "$f" .png | sed 's/.*_side//'); conv "$f" "${key}_side$n" "$key" sides 256 512 "$(name "$key"): sides $n"; done
  for f in "$dir$key"_top*.png; do [ -f "$f" ] || continue
    n=$(basename "$f" .png | sed 's/.*_top//'); conv "$f" "${key}_top$n" "$key" top 512 256 "$(name "$key"): above $n"; done
done
for dir in docs/art/legacy/*/; do
  key=$(basename "$dir")
  for f in "$dir$key"_side*.png; do [ -f "$f" ] || continue
    n=$(basename "$f" .png | sed 's/.*_side//'); conv "$f" "legacy_${key}_side$n" "$key" sides 256 512 "$(name "$key"): sides $n" ", legacy = true"; done
  for f in "$dir$key"_top*.png; do [ -f "$f" ] || continue
    n=$(basename "$f" .png | sed 's/.*_top//'); conv "$f" "legacy_${key}_top$n" "$key" top 512 256 "$(name "$key"): above $n" ", legacy = true"; done
done
for f in docs/art/pilot/*_[0-9].png docs/art/batch/*/*_[0-9].png; do [ -f "$f" ] || continue
  base=$(basename "$f" .png); key=${base%_*}; n=${base##*_}
  conv "$f" "${key}_emblem$n" "$key" emblem 256 256 "$(name "$key"): emblem $n"
done
{
  echo 'local ADDON, ns = ...'
  echo
  echo "-- Rageborn: the painted art shipped in Media\\Art. Generated by tools/make_art.sh; do not edit."
  echo 'ns.PAINTED = {'
  sort "$LIST"
  echo '}'
} > Rageborn/PaintedList.lua
rm -rf "$TMP"
echo "wrote $(ls "$OUT" | wc -l) textures"
